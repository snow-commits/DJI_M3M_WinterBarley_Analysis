"""OpenDroneMap orchestration for four-band M3M reflectance imagery.

The original workflow lived in a hand-maintained bash script with absolute
``/mnt/e/...`` paths and a hard-coded frame count baked in. Here the script is
*rendered* from the resolved configuration instead, so the same pipeline runs
from any checkout on any drive.

Two design points worth knowing:

* The ODM dataset is built from the calibrated single-band reflectance images,
  not from the raw captures. Band order is therefore fixed by the pipeline.
* The saturation placeholders are filled only inside the throw-away ODM working
  copy. Texrecon smears ``-9999`` into large texture artifacts otherwise.

Running this requires WSL with a Docker engine and the ``opendronemap/odm``
image, so it is deliberately separated from the pure-python steps: everything
else in the toolkit works without Docker.
"""

from __future__ import annotations

import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

from m3m import __version__

#: Placeholders are marked with ``@@NAME@@`` instead of ``$NAME`` because the
#: bash source itself is full of ``$variables`` and ``${...}`` expansions.
_SCRIPT_TEMPLATE = r"""#!/usr/bin/env bash
# Generated by m3m v@@VERSION@@ - do not edit by hand.
#
# Builds a four-band M3M orthomosaic with OpenDroneMap.
# Working data is copied onto the WSL filesystem for speed; the source imagery
# on the Windows side is never modified.
set -euo pipefail

work=@@WORK@@
raw_src=@@RAW_SRC@@
reflectance_src=@@REFLECTANCE_SRC@@
project=@@PROJECT@@
dataset=@@DATASET@@
images="$project/$dataset/images"
deliver=@@DELIVER@@
manifest=@@MANIFEST@@
package_root=@@PACKAGE_ROOT@@
repair_log=@@REPAIR_LOG@@

mirror_calibrated=@@MIRROR_CALIBRATED@@
orthophoto_cm=@@ORTHOPHOTO_CM@@
expected_frames=@@EXPECTED_FRAMES@@
odm_image=@@ODM_IMAGE@@

mkdir -p "$work/raw" "$work/radiometric" "$images" "$deliver"
cp -n "$raw_src"/*_MS_*.TIF "$work/raw/" 2>/dev/null || true
cp -n "$reflectance_src"/*@@OUTPUT_SUFFIX@@ "$work/radiometric/"

shopt -s nullglob
corrected=("$work/radiometric"/*@@OUTPUT_SUFFIX@@)
if [[ ${#corrected[@]} -eq 0 ]]; then
    echo "No calibrated reflectance images found in $reflectance_src" >&2
    exit 2
fi
if [[ "$expected_frames" != "0" && ${#corrected[@]} -ne $expected_frames ]]; then
    echo "Expected $expected_frames calibrated band frames, found ${#corrected[@]}" >&2
    exit 2
fi

count=0
if [[ ! -f "$work/.metadata_prepared" ]]; then
    for corrected_path in "${corrected[@]}"; do
        base=$(basename "$corrected_path" @@OUTPUT_SUFFIX@@)
        source_path="$work/raw/$base.TIF"
        if [[ ! -f "$source_path" ]]; then
            echo "Missing source TIFF for $corrected_path" >&2
            exit 3
        fi
        # Copy camera parameters, RTK position/attitude and capture metadata.
        # ExifTool only writes metadata; it does not alter the calibrated pixels.
        exiftool -q -q -overwrite_original -TagsFromFile "$source_path" \
            -XMP -EXIF:GPS:All -EXIF:DateTimeOriginal -EXIF:DateTimeDigitized \
            -EXIF:ExposureTime -EXIF:FocalLength -EXIF:FNumber -EXIF:Make -EXIF:Model \
            "$corrected_path"

        band=${base##*_MS_}
        capture=${base%_MS_*}
        image_link="$images/${capture}_${band}.tif"
        if [[ ! -e "$image_link" ]]; then
            ln "$corrected_path" "$image_link"
        elif ! cmp -s "$corrected_path" "$image_link"; then
            echo "Existing ODM image differs: $image_link" >&2
            exit 4
        fi

        ((count += 1))
        if (( count % 100 == 0 )); then
            echo "XMP attached and linked: $count/${#corrected[@]}"
        fi
    done
    touch "$work/.metadata_prepared"
else
    echo "Reusing prepared XMP metadata and ODM hard links."
fi

if [[ ! -f "$work/.nodata_filled" ]]; then
    # Texrecon spreads the -9999 saturation placeholder into large texture
    # artifacts, so the working copy is filled first (nearest valid pixel).
    docker run --rm \
        --entrypoint /code/venv/bin/python \
        -e PYTHONPATH=/opt/m3m \
        -v "$images:/images" \
        -v "$package_root:/opt/m3m:ro" \
        -v "$manifest:/manifest.csv:ro" \
        -v "$deliver:/audit" \
        "$odm_image" \
        -m m3m fill-nodata \
        --images-dir /images \
        --manifest /manifest.csv \
        --audit-csv /audit/odm_input_filling_audit.csv
    touch "$work/.nodata_filled"
else
    echo "Reusing working copies with saturated pixels filled."
fi

echo "Starting ODM: dataset=$dataset, orthophoto resolution ${orthophoto_cm} cm"
docker run --rm \
    --memory=6g \
    --memory-swap=6g \
    -v "$project:/datasets" \
    "$odm_image" "$dataset" \
    --project-path /datasets \
    --radiometric-calibration none \
    --primary-band NIR \
    --max-concurrency 2 \
    --feature-quality medium \
    --matcher-neighbors 8 \
    --use-hybrid-bundle-adjustment \
    --skip-3dmodel \
    --optimize-disk-space \
    --orthophoto-resolution "$orthophoto_cm" \
    --orthophoto-compression DEFLATE \
    --rerun-from opensfm \
    2>&1 | tee "$repair_log"

dataset_dir="$project/$dataset"
ortho="$dataset_dir/odm_orthophoto/odm_orthophoto.tif"
if [[ ! -f "$ortho" ]]; then
    echo "ODM finished without creating the expected orthophoto: $ortho" >&2
    exit 6
fi
repaired="$deliver/${dataset}_reflectance_orthomosaic_4band_repaired.tif"
cp -f "$ortho" "$repaired"

# Float32 overviews must use lossless compression; ODM's JPEG overview default fails.
docker run --rm \
    --entrypoint /code/SuperBuild/install/bin/gdaladdo \
    -v "$deliver:/output" \
    "$odm_image" \
    -r average \
    --config COMPRESS_OVERVIEW DEFLATE \
    --config BIGTIFF_OVERVIEW IF_SAFER \
    "/output/$(basename "$repaired")" \
    2 4 8 16

if [[ -d "$dataset_dir/odm_report" ]]; then
    cp -a "$dataset_dir/odm_report" "$deliver/"
fi
if [[ -f "$dataset_dir/odm_dem/dsm.tif" ]]; then
    cp -f "$dataset_dir/odm_dem/dsm.tif" "$deliver/${dataset}_dsm.tif"
fi

echo "Repaired orthomosaic copied to $repaired"
"""


@dataclass
class OrthorectificationPlan:
    """Resolved paths and knobs for one ODM run."""

    script_path: Path
    work_dir: str
    raw_src: str
    reflectance_src: str
    project: str
    deliver: str
    manifest: str
    expected_frames: int | None = None
    odm_image: str = "opendronemap/odm:latest"


class OrthorectificationError(RuntimeError):
    """Raised when the ODM step cannot be prepared or launched."""


def to_wsl_path(path: Path | str, *, distro_mount_root: str = "/mnt") -> str:
    """Convert a Windows path to its WSL equivalent.

    ``E:\\data\\field`` becomes ``/mnt/e/data/field``. Paths that already look
    like POSIX paths are returned unchanged, so this is safe on Linux hosts.
    """
    text = str(path)
    if text.startswith("/"):
        return text
    drive, _, tail = text.partition(":")
    if not tail or len(drive) != 1:
        raise OrthorectificationError(
            f"Cannot convert {text!r} to a WSL path. Pass an absolute Windows path "
            f"such as E:\\data\\field, or run the pipeline inside WSL directly."
        )
    tail = tail.replace("\\", "/").lstrip("/")
    return f"{distro_mount_root}/{drive.lower()}/{tail}"


def package_root() -> Path:
    """Directory that must be importable for ``python -m m3m`` to work."""
    return Path(__file__).resolve().parent.parent


def render_script(
    *,
    work_dir: Path | str,
    raw_src: Path | str,
    reflectance_src: Path | str,
    project: Path | str,
    deliver: Path | str,
    manifest: Path | str,
    dataset: str,
    output_suffix: str,
    orthophoto_resolution_cm: int,
    expected_frames: int | None = None,
    odm_image: str = "opendronemap/odm:latest",
    mirror_calibrated: bool = True,
) -> str:
    """Render the ODM bash script with concrete paths substituted in."""
    replacements = {
        "@@VERSION@@": __version__,
        "@@WORK@@": to_wsl_path(work_dir),
        "@@RAW_SRC@@": to_wsl_path(raw_src),
        "@@REFLECTANCE_SRC@@": to_wsl_path(reflectance_src),
        "@@PROJECT@@": to_wsl_path(project),
        "@@DELIVER@@": to_wsl_path(deliver),
        "@@MANIFEST@@": to_wsl_path(manifest),
        "@@PACKAGE_ROOT@@": to_wsl_path(package_root()),
        "@@REPAIR_LOG@@": to_wsl_path(Path(deliver) / "odm_processing_repair.log"),
        "@@DATASET@@": dataset,
        "@@OUTPUT_SUFFIX@@": output_suffix,
        "@@ORTHOPHOTO_CM@@": str(int(orthophoto_resolution_cm)),
        "@@EXPECTED_FRAMES@@": str(int(expected_frames) if expected_frames else 0),
        "@@ODM_IMAGE@@": odm_image,
        "@@MIRROR_CALIBRATED@@": "1" if mirror_calibrated else "0",
    }
    script = _SCRIPT_TEMPLATE
    for token, value in replacements.items():
        script = script.replace(token, value)
    return script


def write_script(plan_script_path: Path | str, script: str) -> Path:
    """Write the rendered script with a shebang-friendly line ending."""
    path = Path(plan_script_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    # LF endings: CRLF breaks `bash script.sh` inside WSL.
    path.write_text(script.replace("\r\n", "\n"), encoding="utf-8", newline="\n")
    return path


def run_via_wsl(
    script_path: Path | str,
    *,
    distro: str = "Ubuntu",
    user: str = "root",
    check: bool = True,
) -> subprocess.CompletedProcess[bytes]:
    """Execute a rendered script through ``wsl.exe``."""
    if shutil.which("wsl") is None:
        raise OrthorectificationError(
            "wsl.exe was not found. This step needs WSL with a Docker engine; "
            "install it or run the script inside WSL manually:\n"
            f"  bash {to_wsl_path(script_path)}"
        )
    command = [
        "wsl.exe",
        "-d",
        distro,
        "-u",
        user,
        "--",
        "bash",
        to_wsl_path(script_path),
    ]
    return subprocess.run(command, check=check)
