"""Shared fixtures.

Real M3M flight data is proprietary, so every test runs against the synthetic
dataset generated by :mod:`m3m.synthetic`. That keeps the suite fast, offline and
deterministic, and it means a fresh clone can verify the whole toolkit.
"""

from __future__ import annotations

import pytest

from m3m import synthetic

#: Small images keep the suite quick while still forcing multi-window reads.
TEST_SHAPE = (96, 128)
TEST_PANEL_ROI = (10, 20, 50, 70)


@pytest.fixture(scope="session")
def raw_dataset(tmp_path_factory: pytest.TempPathFactory):
    """Two complete capture groups with panels and RGB companions."""
    root = tmp_path_factory.mktemp("synthetic_raw")
    return synthetic.generate_raw_dataset(
        root, groups=2, shape=TEST_SHAPE, panel_roi=TEST_PANEL_ROI, with_rgb=True
    )


@pytest.fixture(scope="session")
def orthomosaic(tmp_path_factory: pytest.TempPathFactory):
    """A five-band reflectance orthomosaic plus its field boundary."""
    root = tmp_path_factory.mktemp("synthetic_ortho")
    return synthetic.generate_orthomosaic(root, shape=TEST_SHAPE)


@pytest.fixture()
def project_dir(tmp_path, raw_dataset):
    """A self-contained project directory with a written ``m3m.toml``.

    The orthomosaic is regenerated inside *tmp_path* rather than reused from the
    session fixture so each test owns every file it touches.
    """
    ortho = synthetic.generate_orthomosaic(tmp_path, shape=TEST_SHAPE)
    config_path = synthetic.write_config(
        tmp_path / "m3m.toml", raw_dataset, orthomosaic=ortho
    )
    return tmp_path, config_path
